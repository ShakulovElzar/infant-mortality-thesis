"""Build reference/columns.csv and reference/layout_differences.md from the 8 user guides.

Run: python -I src/build_columns.py   (needs pdftotext and docs/guides/*.pdf)
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from cdc_layout import parse_layout, check_tiling  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "reference"
YEARS = range(2016, 2024)

layouts = {}
for c in YEARS:
    rows = [r for r in parse_layout(c) if r["public"]]
    for length in (1346, 1743):
        problems = check_tiling(parse_layout(c), length)
        assert not problems, (c, length, problems)
    layouts[c] = {r["name"]: r for r in rows}

names = sorted({n for L in layouts.values() for n in L},
               key=lambda n: min(L[n]["start"] for L in layouts.values() if n in L))
OUT.mkdir(exist_ok=True)
with open(OUT / "columns.csv", "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["name", "start_2023", "end_2023", "file", "description", "missing_codes_auto",
                "years_present", "position_by_year_if_different", "codes"])
    for n in names:
        ref = layouts[2023].get(n) or next(L[n] for L in layouts.values() if n in L)
        years = [c for c in YEARS if n in layouts[c]]
        pos = {c: (layouts[c][n]["start"], layouts[c][n]["end"]) for c in years}
        differs = {c: p for c, p in pos.items() if p != (ref["start"], ref["end"])}
        w.writerow([n, ref["start"] if n in layouts[2023] else "", ref["end"] if n in layouts[2023] else "",
                    "denominator+numerator" if ref["end"] <= 1346 else "numerator only",
                    ref["description"], ref["missing"],
                    f"{years[0]}-{years[-1]}" if years == list(range(years[0], years[-1] + 1)) else ",".join(map(str, years)),
                    "; ".join(f"{c}:{s}-{e}" for c, (s, e) in differs.items()), ref["codes"]])

# Differences report
lines = ["# Layout differences between cohort years", "",
         "Generated by `src/build_columns.py` from the CDC user guides in `docs/guides/`. "
         "Every year's layout covers positions 1–1346 (births) and 1–1743 (deaths) with no gap or overlap of fields.", ""]
only = defaultdict(list)
for n in names:
    yrs = tuple(c for c in YEARS if n in layouts[c])
    if yrs != tuple(YEARS):
        only[yrs].append(n)
lines += ["## Fields not present in all 8 years", "", "| Years | Fields |", "|---|---|"]
for yrs, ns in sorted(only.items()):
    lines.append(f"| {yrs[0]}–{yrs[-1]} | {', '.join(f'`{x}`' for x in ns)} |" if len(yrs) > 1 else f"| {yrs[0]} | {', '.join(f'`{x}`' for x in ns)} |")
moved = [n for n in names if len({(layouts[c][n]['start'], layouts[c][n]['end']) for c in YEARS if n in layouts[c]}) > 1]
lines += ["", "## Fields whose position changes", ""]
lines += [f"- `{n}`: " + ", ".join(f"{c} {layouts[c][n]['start']}-{layouts[c][n]['end']}" for c in YEARS if n in layouts[c]) for n in moved] or ["None."]
(OUT / "layout_differences.md").write_text("\n".join(lines) + "\n")
print(len(names), "public fields;", sum(len(v) for v in only.values()), "not in all years;", len(moved), "moved")
